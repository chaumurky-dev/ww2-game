#!/usr/bin/env python3
"""Full pipeline: land (Natural Earth) -> sea zones (Voronoi) -> verify -> map_geometry.json + preview.svg + MISMATCHES.md"""
import json, os, sys
from shapely.ops import polylabel
from shapely.geometry import Point
import check, preview, proj, sea
from geom import polys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "crates", "web", "assets", "map_geometry.json")

def best_label(g):
    best = None
    for p in polys(g):
        pt = polylabel(p, 0.5)
        r = p.exterior.distance(pt)
        if best is None or r > best[0]:
            best = (r, pt, p)
    return best

def main():
    land_px, zones, water, m, found, exp, res = check.run(rebuild="--rebuild" in sys.argv)
    locs = {}
    labels = {}
    for kind, items in (("land", land_px), ("sea", zones)):
        for k, g in items.items():
            if k in ("__decor__", "__void__") or g.is_empty:
                continue
            r, pt, poly = best_label(g)
            lx, ly = round(pt.x, 1), round(pt.y, 1)
            ax, ay = lx, ly + 12
            if not poly.contains(Point(ax, ay)) or poly.exterior.distance(Point(ax, ay)) < 4:
                ax, ay = lx, ly
            b = g.bounds
            locs[k] = {"kind": kind, "path": proj.path_d(g), "label": [lx, ly], "anchor": [round(ax, 1), round(ay, 1)],
                       "bbox": [round(v, 1) for v in b]}
            labels[k] = (lx, ly)
    decor = proj.path_d(land_px["__decor__"]) if "__decor__" in land_px else ""
    out = {"view_box": "0 0 2000 1000", "projection": "miller", "locations": locs, "decor": decor}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(out, open(OUT, "w"), separators=(",", ":"))
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB; locations:", len(locs))
    preview.write_preview(land_px, zones, m, labels)
    # mismatch report
    ls = lambda kind, key: sorted(x for x in res[key] if x[0] == kind)
    lines = ["# Geometry/topology mismatches", "",
             "Generated by `build.py`. Contact = shared boundary length >= 3 px in the 2000x1000 viewBox.",
             "Geometry comes from real (modern) geography, so the abstract board topology cannot be matched everywhere.",
             "Declared virtual links (canals/straits, see `sea_zone_seeds.json`) are treated as satisfied: Suez, Panama, Black Sea straits, Tehuantepec.",
             "Remaining EXTRA contacts are mostly unavoidable coastlines (Java Sea, Malacca Strait, Gulf of Tonkin, Corsica, Cabinda/Congo mouth, Bering/Okhotsk coasts).", ""]
    for kind in ("land-sea", "sea-sea", "land-land"):
        mi, ex = ls(kind, "missing"), ls(kind, "extra")
        note = " (informational only; not iterated on)" if kind == "land-land" else ""
        lines.append(f"## {kind}{note}: {len(mi)} missing, {len(ex)} extra")
        lines.append("")
        for x in mi: lines.append(f"- MISSING: {x[1][0]} -- {x[1][1]}")
        for x in ex: lines.append(f"- EXTRA: {x[1][0]} -- {x[1][1]} ({x[2]} px)")
        lines.append("")
    open(os.path.join(HERE, "MISMATCHES.md"), "w").write("\n".join(lines))
    print({k: (len([x for x in res['missing'] if x[0]==k]), len([x for x in res['extra'] if x[0]==k])) for k in ("land-sea","sea-sea","land-land")})

main()
